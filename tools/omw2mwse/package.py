"""Build an MWSE mod folder that hosts an unmodified OpenMW Lua mod via omwcompat."""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
from pathlib import Path

from . import __version__
from .scan import ModScan, find_lua_files, find_omwscripts, load_manifest, normalize_mesh, render_markdown, scan_mod

HERE = Path(__file__).resolve().parent
RUNTIME_LIB = HERE.parent.parent / "runtime" / "MWSE" / "lib"
MARKER = ".omw2mwse-output"
MAX_MESH = 31


class PackageError(Exception):
    pass


def default_slug(name: str) -> str:
    caps = re.findall(r"[A-Z0-9]", name)
    slug = "".join(caps).lower() if len(caps) >= 2 else re.sub(r"[^a-z0-9]", "", name.lower())
    return (slug or "mod")[:8]


def mesh_alias(slug: str, normalized: str) -> str:
    h = hashlib.sha1(normalized.encode("utf-8")).hexdigest()[:8]
    alias = f"omwc/{slug}/{h}.nif"
    if len(alias) > MAX_MESH:
        raise PackageError(f"alias {alias} too long; use a shorter --slug")
    return alias


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def write_text(p: Path, text: str) -> None:
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:  # UTF-8, no BOM, LF
        f.write(text)


def render_main(name: str, scripts, meshmap: dict[str, str]) -> str:
    lines = [
        f"-- {name}: MWSE loader generated by omw2mwse {__version__}.",
        "-- The original OpenMW Lua lives untouched in Data Files/MWSE/omw/" + name + "/",
        "-- and is hosted by the omwcompat runtime (Data Files/MWSE/lib/omwcompat).",
        "-- Generated file: re-run `omw2mwse package` instead of editing.",
        "local ok, omwcompat = pcall(require, \"omwcompat\")",
        "if not ok then",
        f"    mwse.log(\"[{name}] omwcompat runtime is missing or failed to load: %s\", tostring(omwcompat))",
        "    return",
        "end",
        "",
        "omwcompat.register({",
        f"    mod = {lua_str(name)},",
        f"    root = {lua_str('Data Files/MWSE/omw/' + name + '/')},",
        "    scripts = {",
    ]
    for s in scripts:
        flags = ", ".join(lua_str(f) for f in s.flags)
        lines.append(f"        {{ flags = {{ {flags} }}, path = {lua_str(s.path)} }},")
    lines.append("    },")
    lines.append("    meshmap = {")
    for src, dst in sorted(meshmap.items()):
        lines.append(f"        [{lua_str(src)}] = {lua_str(dst)},")
    lines.append("    },")
    lines.append("})")
    return "\n".join(lines) + "\n"


def render_metadata(name: str, src_name: str) -> str:
    return (
        "[package]\n"
        f"name = \"{name}\"\n"
        f"description = \"{src_name} (OpenMW Lua) hosted on MWSE via omwcompat; packaged by omw2mwse {__version__}\"\n"
        "\n"
        "[tools.mwse]\n"
        f"lua-mod = \"{name}\"\n"
    )


def package(src: Path, out: Path, name: str | None = None, slug: str | None = None, with_runtime: bool = True,
            meshes_from: Path | None = None, force: bool = False, manifest: dict | None = None) -> dict:
    src, out = Path(src).resolve(), Path(out).resolve()
    if not src.is_dir():
        raise PackageError(f"source {src} is not a directory")
    if out == src or src in out.parents or out in src.parents:
        raise PackageError("output must not be inside the source (or vice versa)")
    manifest = manifest or load_manifest()
    scan: ModScan = scan_mod(src, manifest, name=name)
    name = name or src.name
    if not re.fullmatch(r"[A-Za-z0-9_\-]+", name):
        raise PackageError(f"mod name {name!r} must be [A-Za-z0-9_-]")
    slug = slug or default_slug(name)
    if not scan.scripts:
        raise PackageError("no .omwscripts declarations found; nothing to host")
    if out.exists():
        if not force:
            raise PackageError(f"{out} exists (use --force to replace a previous omw2mwse output)")
        if not (out / MARKER).exists():
            raise PackageError(f"{out} exists and was not created by omw2mwse; refusing to replace it")
        shutil.rmtree(out)

    before = {p: sha256(p) for p in sorted(src.rglob("*")) if p.is_file()}
    data = out / "Data Files"
    omw_root = data / "MWSE" / "omw" / name
    notes: list[str] = []

    # 1. Lua + .omwscripts, copied byte-for-byte
    copied: list[tuple[Path, Path]] = []
    lua_files = find_lua_files(src)
    declared = {s.path.lower(): s.path for s in scan.scripts}
    by_base: dict[str, list[str]] = {}
    for d in declared.values():
        by_base.setdefault(Path(d).name.lower(), []).append(d)
    for p in lua_files:
        rel = p.relative_to(src).as_posix()
        target_rel = rel
        if rel.lower() not in declared:
            cands = by_base.get(p.name.lower(), [])
            if len(cands) == 1 and not (src / cands[0]).exists():
                target_rel = cands[0]
                notes.append(f"source has {rel} but .omwscripts declares {cands[0]}; placed at the declared path")
        copied.append((p, omw_root / target_rel))
    for om in find_omwscripts(src):
        copied.append((om, omw_root / om.relative_to(src).as_posix()))
    l10n = [p for p in src.rglob("*") if p.is_file() and "l10n" in [x.lower() for x in p.relative_to(src).parts]]
    for p in l10n:
        copied.append((p, omw_root / p.relative_to(src).as_posix()))
    for a, b in copied:
        b.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(a, b)
        if sha256(a) != sha256(b):
            raise PackageError(f"copy verification failed for {a}")

    # 2. mesh aliases (R4)
    meshmap: dict[str, str] = {}
    alias_rows: list[tuple[str, str, str]] = []
    for m in scan.meshes:
        n = normalize_mesh(m)
        if len(n) > MAX_MESH and n not in meshmap:
            meshmap[n] = mesh_alias(slug, n)
    for n, a in sorted(meshmap.items()):
        status = "not copied (copy on install)"
        if meshes_from:
            srcmesh = Path(meshes_from) / n
            if srcmesh.is_file():
                dst = data / "meshes" / a
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(srcmesh, dst)
                status = "copied"
            else:
                status = "source mesh missing"
        alias_rows.append((n, a, status))

    # 3. loader, metadata, runtime
    write_text(data / "MWSE" / "mods" / name / "main.lua", render_main(name, scan.scripts, meshmap))
    write_text(data / f"{name}-metadata.toml", render_metadata(name, src.name))
    if with_runtime:
        (data / "MWSE" / "lib").mkdir(parents=True, exist_ok=True)
        shutil.copyfile(RUNTIME_LIB / "omwcompat.lua", data / "MWSE" / "lib" / "omwcompat.lua")
        rdir = data / "MWSE" / "lib" / "omwcompat"
        rdir.mkdir(parents=True, exist_ok=True)
        for f in sorted((RUNTIME_LIB / "omwcompat").iterdir()):
            if f.is_file():
                shutil.copyfile(f, rdir / f.name)

    # 4. reports
    rows = ["# Mesh aliases (R4: Morrowind record mesh paths are limited to 31 chars)",
            "# source (relative to Data Files/meshes)\talias (relative to Data Files/meshes)\tstatus"]
    rows += [f"{a}\t{b}\t{c}" for a, b, c in alias_rows]
    write_text(out / "MESH-ALIASES.txt", "\n".join(rows) + "\n")
    report = [f"# omw2mwse package report: {name}", "",
              f"- Source: `{src}` (left unmodified; verified by SHA-256 before/after)",
              f"- omw2mwse {__version__}, runtime manifest {manifest.get('version')}",
              f"- Scan verdict: **{scan.verdict}**",
              f"- Mesh aliases: {len(alias_rows)} (see MESH-ALIASES.txt)", ""]
    if notes:
        report += ["## Notes", ""] + [f"- {n}" for n in notes] + [""]
    report.append("## Files")
    report.append("")
    for a, b in copied:
        report.append(f"- `{b.relative_to(out).as_posix()}` <- `{a.relative_to(src).as_posix()}` (sha256 {sha256(b)[:12]})")
    report.append("")
    report.append(render_markdown([scan], title="Scan").replace("# Scan", "## Scan", 1))
    write_text(out / "OMW2MWSE-REPORT.md", "\n".join(report))
    write_text(out / MARKER, json.dumps({"tool": "omw2mwse", "version": __version__, "source": str(src)}) + "\n")

    after = {p: sha256(p) for p in sorted(src.rglob("*")) if p.is_file()}
    if before != after:
        raise PackageError("source tree changed during packaging (this is a bug)")
    return {"out": str(out), "name": name, "slug": slug, "verdict": scan.verdict, "aliases": alias_rows,
            "copied": [(str(a), str(b)) for a, b in copied], "notes": notes, "blockers": scan.blockers}
