#!/usr/bin/env python3
"""Write docs/SURVEY-2026-11.md, docs/survey/*.csv, and the Known mods table in docs/GAPS.md (dej (dejunai)).

  python3 scripts/survey_report.py <survey dir> docs
  python3 scripts/survey_report.py --gaps-table [docs/survey/mods.csv] [docs/GAPS.md]
"""
import json, csv, sys, collections, re
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from survey_aggregate import norm_blocker, family
from survey_gaps import write_gaps_table, maybe_run_gaps_table_only
if maybe_run_gaps_table_only(sys.argv[1:]):
    sys.exit(0)
S = Path(sys.argv[1]); DOCS = Path(sys.argv[2])
units = json.load(open(S / 'units.json')); agg = json.load(open(S / 'agg/aggregate.json'))
sv = json.load(open(S / 'agg/scope_view.json')); deg = json.load(open(S / 'agg/degraded.json'))
real = [u for u in units if u['counted']]
v = collections.Counter(u['verdict'] for u in real)
short = lambda i: i.split(':', 1)[-1]
byid = {u['id']: u for u in real}
def names(ids, n=8):
    ids = list(ids); t = ', '.join(short(i) for i in ids[:n])
    return t + (f' (+{len(ids) - n})' if len(ids) > n else '')
# mod table csv
with open(DOCS / 'survey/mods.csv', 'w', newline='') as fh:
    w = csv.writer(fh, lineterminator='\n')
    w.writerow(['mod', 'repo_id', 'source_url', 'verdict', 'n_blockers', 'gap_families', 'counted', 'note'])
    for u in sorted(units, key=lambda u: (not u['counted'], u['id'].lower())):
        fams = sorted({family(*norm_blocker(b)) for b in u['blockers']})
        note = ('duplicate of ' + u['dup_of']) if 'dup_of' in u else ''
        if not u['counted'] and not note:
            note = 'excluded: engine resource, test fixture, engine fork, no .omwscripts declarations, or no Lua'
        w.writerow([u['mod'] + (' [' + u['variant'] + ']' if u.get('variant') and u['variant'] not in ('..', '.') else ''), u['repo'], u['url'], u['verdict'], len(u['blockers']), ' ; '.join(fams), 'yes' if u['counted'] else 'no', note])
L = []
A = L.append
A('# omw2mwse dry-run survey, 2026-11-27')
A('')
A('*dej (dejunai). Generated by `scripts/survey_*.py`. Converter under test: omw2mwse 0.3.2 with omwcompat 0.5.0 (main f2e9130). Dry run only: nothing was converted, staged or deployed.*')
A('')
A('## Method')
A('')
A('- Sources: the repo test corpus (10 Nexus-sourced mods Dej downloaded earlier, plus Leave The Lights Off), every `modding-openmw` GitLab project with an `.omwscripts` file (57 repos, shallow clones of HEAD), GitHub repo searches (topics `openmw`, `openmw-lua`, `openmw-mod`, `morrowind`, name/description/readme queries, about 100 repos with an `.omwscripts`), six more GitLab/GitHub repos linked from modding-openmw.com, and the modding-openmw.com `openmw-lua` tag (241 mod pages, 190 of them Nexus-only; see below).')
A('- Per repo: `omw2mwse --staged-root <repo> --result-json <f> --dry-run` (the tidy call) and `omw2mwse scan --json --no-installs --no-openmw <repo>`. Repos that hold several OpenMW mods give one verdict per mod (`mods[]`). Repos with several source folders (exit 2) were rerun once per folder with `--source`.')
A('- Counted: %d distinct mods. Not counted: OpenMW engine resource folders (`builtin`, `test_lua_api`, `morrowind_tests` inside engine forks), test/smoke/dump fixtures, engine forks and tools, repos with no active `.omwscripts` lines, mods with no Lua, and cross-repo duplicates (same mod name; Leave The Lights Off is counted once).' % len(real))
A('- Nexus mods cannot be downloaded without a login, so none were fetched. The 241 Lua-tagged mod pages on modding-openmw.com are listed in `docs/survey/nexus-candidates-not-surveyed.csv` for a manual round (only Dej can download those).')
A('- Per-mod table with source URLs: `docs/survey/mods.csv`.')
A('')
A('## Verdicts')
A('')
A('| verdict | mods | share |')
A('|---|---|---|')
for k in ('ready', 'blocked', 'none'):
    A(f'| {k} | {v.get(k, 0)} | {100 * v.get(k, 0) / len(real):.0f}% |')
A(f'| **total counted** | **{len(real)}** | |')
A('')
A('`none` is 0 because repos with no active `.omwscripts` lines or no Lua were left out of the count (a few; see mods.csv). Exit codes over %d distinct inputs: 0 (ready/none) and 1 (blocked) as expected, 2 for the cases listed under "Exit 2", and no 70/64/3. No Python traceback appeared in any run or scan, so the converter never crashed.' % len(json.load(open(S / 'runs_all.json'))))
A('')
A('Ready mods (%d): ' % v['ready'] + names([u['id'] for u in real if u['verdict'] == 'ready'], 40) + '.')
A('')
nf = collections.Counter(len({family(*norm_blocker(b)) for b in u['blockers']}) for u in real if u['verdict'] == 'blocked')
A('How far blocked mods are from ready (number of distinct gap families each needs): ' + ', '.join(f'{k}: {nf[k]}' for k in (1, 2, 3)) + f', 4 or more: {sum(c for k, c in nf.items() if k >= 4)}. So {nf[1]} mods are one family away, {nf[1]+nf[2]} are two or fewer away.')
A('')
A('## Ranked gaps (families)')
A('')
A('"Blocks" = blocked mods that hit the gap. "Alone" = mods that would turn ready if only this gap were filled. "+1" = mods that would turn ready if this gap and one other family were filled. Families group related API names (for example every `openmw.ui.*` widget, `I.MWUI` template and `openmw_aux.ui` call is one UI-layout family); single APIs outside a family keep their own row.')
A('')
A('| # | gap | blocks | alone | +1 | would turn ready alone |')
A('|---|---|---|---|---|---|')
for i, r in enumerate(agg['fam'][:20], 1):
    A(f"| {i} | {r['gap']} | {r['blocks']} | {len(r['alone_unlocks'])} | {len(r['near'])} | {names(r['alone_unlocks'], 4) or '-'} |")
A('')
A('### Single APIs (finest grain, top 15)')
A('')
A('| # | API | blocks | alone |')
A('|---|---|---|---|')
for i, r in enumerate([r for r in agg['fine'] if not re.search(r'openmw\.ui|MWUI|menuscope|openmw_aux\.ui', r['gap'])][:15], 1):
    A(f"| {i} | `{r['gap']}` | {r['blocks']} | {len(r['alone_unlocks'])} |")
A('')
A('## Best order to fill gaps')
A('')
A('Greedy by newly ready mods, all %d blocked mods (UI layouts allowed):' % v['blocked'])
A('')
for s in agg['greedy_fam']:
    A(f"1. {s['add']}: +{len(s['new_ready'])} ({names(s['new_ready'], 5)}), cumulative +{s['cumulative_ready']}")
A('')
A('Same, but only the %d blocked mods that do not need UI layouts (the HUD/UI rule keeps layouts out of scope):' % sv['inscope_blocked'])
A('')
for s in sv['greedy_inscope']:
    A(f"1. {s['add']}: +{len(s['new_ready'])} ({names(s['new_ready'], 5)}), cumulative +{s['cumulative_ready']}")
A('')
A('## Stubbed or partial APIs (degrade, do not block)')
A('')
A('Number of mods that use each partial or stub API. Taken from the per-repo scan, so it includes files not declared in `.omwscripts`; read it as an upper bound.')
A('')
A('| # | API | status | mods | what differs |')
A('|---|---|---|---|---|')
for i, r in enumerate(deg[:15], 1):
    A(f"| {i} | `{r['api']}` | {r['status']} | {r['repos']} | {r['note'][:110].replace('|', '/')} |")
A('')
A('## Finding: 0.5.0 manifest sync')
A('')
lag = agg['manifest_lag_blocked_by_any']
A("omwcompat 0.5.0 lists `openmw.animation`, `I.AnimationController.*` and `self.controls.*` as partial or stub (no longer unsupported), so scan and convert no longer block on the calls the runtime already ports or degrades. One counted mod turned ready: PetMudcrab (https://github.com/TinkerSnail/pinchito), which was blocked only on animation. Thieves Pickpocket 1.5.5 dropped those blockers (20 down to 15) but is still blocked on UI layouts and a MENU script. " + (
    "No counted mod is now blocked only on those synced families."
    if not lag else
    ("%d mods still hit animation APIs that 0.5.0 does not cover (%s); none of them would turn ready from that alone." % (len(lag), names(lag, 8)))
))
A('')
A('## Exit 2 and crashes')
A('')
A('No exit 70 (internal error), 64 or 3 and no tracebacks. Exit 2 (failed) occurred for these inputs; none is a converter bug, but several are things tidy will meet:')
A('')
A('- **Several source folders** (`<Mod>: 2 different source folders ...; pick one with --source`): the call is all-or-nothing, so one mod folder holding a legacy copy or a second build cannot be converted without `--source`. Repro: `omw2mwse --staged-root <gitlab light-hotkey checkout> --result-json r.json --dry-run` (folders `.` and `legacy`). Also seen in pharis-magicka-regeneration, carefree_leveling (`0.48`, `0.49 or later`), Expedition32 (two patches), kinetic, and the four corpus mods that keep `_archive/full`. A relative `--source` is resolved against the current directory, not the staged root, and `--source .` scans the whole current directory.')
A('- **Existing file not ours** (`conflict`): dev-chenxing/MyManor already ships `MyManor-metadata.toml` and an `MWSE/` folder next to its `.omwscripts` (a hybrid mod). Repro: dry-run on the checkout of https://github.com/dev-chenxing/MyManor. This is the guarded behaviour, but tidy should skip hybrids rather than offer `--adopt-existing`.')
A('- **Every line commented out** (`no .omwscripts declarations found; nothing to host`): madsbuvi/openmw-lua-test-mods (`spellcast_mods.omwscripts` lines all start with `#`). Correct, but the message does not say the lines were commented out.')
A('- **Case collision on Linux**: Tae410/Stance has `scripts/Stance/config.lua` and `scripts/stance/config.lua`; the converter reports `two source files map to scripts/stance/config.lua` (fine on a case-insensitive Windows tree, only appears here).')
A('- Engine forks and their `builtin` mods (isowind, bru, openmw-enhanced, openmw-portal, Fetcher-Simulator) dry-run as 269-block mods; they were excluded from the counts.')
A('')
A('## Recommendations for omwcompat')
A('')
A('The 0.5.0 manifest sync is done (see above). The remaining highest-value additions:')
A('')
A('1. **Magic read API (core.magic records and enums, Actor spells/activeSpells/activeEffects, selected spell).** Biggest non-UI gap: it blocks %d mods and is the first greedy pick (+3 alone, more with others). Candidates to map onto in MWSE: `tes3.getMagicEffect`, the mobile `currentSpell` field, `activeMagicEffectList` and the object spell lists.' % next(r['blocks'] for r in agg['fam'] if r['gap'].startswith('magic')))
A('2. **I.UI mode functions (getMode/setMode/addMode/removeMode) and MENU settings-only scripts.** I.UI is not HUD drawing; `getMode` is mostly "is a menu open", which `tes3ui.menuMode()` can answer. MENU scripts are a wide blocker and the runtime already recognizes settings-only MENU scripts (0.4.1), so the scanner could host MENU scripts whose only calls are settings and `ui.showMessage`.')
A('3. **Input handlers (`registerTrigger`/`registerTriggerHandler`, controller buttons, `onInputAction`, `onMouseWheel`)**, mapped to MWSE `keyDown`/`mouseWheel` events and the input controller.')
A('4. **Skill and stat records (`core.stats.Skill/Attribute.records`, NPC races/classes, `I.SkillProgression`) and `I.ItemUsage.addHandlerForType`.** Each unlocks a few mods on its own and the records are plain data reads.')
A('5. **Remaining animation APIs the 0.5.0 port does not cover** (`openmw.animation.play`, `getBoneTransform`), only after the items above: they still appear on a couple of large mods that also need many other families.')
A('')
A('UI layouts (`ui.create`, `ui.content`, `TYPE.*`, I.MWUI templates) remain the top blocker (85 mods) but the HUD/UI rule keeps them out; they appear only as a ceiling: no more than the in-scope numbers above can be reached without them. Camera (48) and `I.Combat` hit handlers (23) come next.')
A('')
A('## Reproduce')
A('')
A('```')
A('python3 scripts/survey_run.py bin/omw2mwse <dir of clones> <out dir>   # dry-run + scan per repo')
A('python3 scripts/survey_units.py                                         # builds units.json (paths set at top)')
A('python3 scripts/survey_aggregate.py units.json agg                      # rankings, greedy order, manifest-lag view')
A('python3 scripts/survey_report.py <survey dir> docs                      # this report and mods.csv')
A('python3 scripts/survey_report.py --gaps-table                           # Known mods table in docs/GAPS.md')
A('```')
(DOCS / 'SURVEY-2026-11.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print(len(L))
# keep GAPS.md in sync when the survey report (and mods.csv) is regenerated
write_gaps_table(DOCS / 'survey/mods.csv', DOCS / 'GAPS.md')
